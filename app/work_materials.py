def derive(reference: dict[str, list[dict[str, Any]]]) -> dict[WorkType, tuple[Material, ...]]:
    out = {}
    for work, items in reference.items():
        found: list[Material] = []
        for item in items:
            if item["role"] in NOT_IN_ESTIMATE_ROLES:
                continue
            for m in ITEM_MATERIALS[item["item"]]:
                if m not in found:
                    found.append(m)
        out[WorkType(work)] = tuple(found)
    return out
