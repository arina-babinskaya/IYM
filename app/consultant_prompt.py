def bounded_messages(messages: list[dict[str, str]], max_messages: int, max_chars: int) -> list[dict[str, str]]:
    """Keep newest complete turns inside both count and character limits."""
    selected: list[dict[str, str]] = []
    used = 0
    for message in reversed(messages[-max_messages:]):
        size = len(message["content"])
        if selected and used + size > max_chars:
            break
        selected.append(message)
        used += size
    return list(reversed(selected))


ROOM_TITLE_PATTERNS = (
    ("Кухня", r"\bкухн(?:я|ю|е|и|ей)\b"),
    ("Гостиная", r"\bгостин(?:ая|ую|ой|ою)\b"),
    ("Детская", r"\bдетск(?:ая|ую|ой|ою)(?:\s+комнат\w*)?\b"),
    ("Спальня", r"\bспальн(?:я|ю|е|и|ей)\b"),
    ("Ванная", r"\bванн(?:ая|ую|ой|ою|а|у|е|ы)\b|\bсануз(?:ел|ла|ле|лом)\b"),
    ("Прихожая", r"\bприхож(?:ая|ую|ей)\b|\bкоридор\w*\b"),
    ("Кабинет", r"\bкабинет\w*\b"),
    ("Столовая", r"\bстолов(?:ая|ую|ой)\b"),
    ("Постирочная", r"\bпостирочн\w*\b|\bкладов(?:ая|ую|ой)\b"),
    ("Балкон", r"\bбалкон\w*\b|\bлоджи\w*\b"),
)


def automatic_chat_title(message: str) -> str:
    """Derive a conservative Russian title without an extra provider request."""
    normalized = " ".join(message.lower().split())
    rooms = [title for title, pattern in ROOM_TITLE_PATTERNS if re.search(pattern, normalized)]
    if re.search(r"\b(?:вс(?:я|ей|ю)|цел\w*)\s+квартир\w*\b|\bремонт\w*\s+квартир\w*\b", normalized):
        return "Вся квартира"
    if len(rooms) > 1:
        return "Несколько комнат"
    if rooms:
        return rooms[0]
    topics = (
        ("Подбор обоев", r"\bобо(?:и|ев|ями|ях)\b"),
        ("Выбор пола", r"\bпол(?:а|у|ом|ы|ов)?\b|\bнапольн\w*\b"),
        ("Отделка стен", r"\bстен\w*\b|\bкраск\w*\b"),
        ("Освещение", r"\bосвещени\w*\b|\bсветильник\w*\b"),
        ("Консультация по материалам", r"\bматериал\w*\b"),
        ("Планирование ремонта", r"\bремонт\w*\b|\bотделк\w*\b"),
    )
    for title, pattern in topics:
        if re.search(pattern, normalized):
            return title
    return "Консультация по ремонту"
